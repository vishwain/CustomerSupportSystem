"""Stage 1, Section 5: audit of the four data files.

Usage:
    python docs/data_audit.py [--data-dir data] [--output docs/data_audit.md]

Checks record counts, field names, private-data patterns in free text,
customer identity stability, duplicate ticket texts, label conflicts and
ground-truth linkage. Standard library only. Output is written to the
markdown file and printed.
"""

import argparse
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

PATTERNS = {
    "email": r"[\w.+-]+@[\w-]+\.[\w.]+",
    "phone": r"\+?\d[\d\s().-]{8,}\d",
    "ip_address": r"\b\d{1,3}(?:\.\d{1,3}){3}\b",
    "url": r"https?://\S+",
    "card_like": r"\b(?:\d[ -]?){13,16}\b",
    "key_like": r"\b(?:sk|pk|key|token|api)[-_][A-Za-z0-9]{8,}\b|AKIA[0-9A-Z]{16}",
    "long_secret": r"\b[A-Za-z0-9+/]{32,}\b",
    "customer_id": r"CUST-\d+",
}


def load(d, name):
    return json.loads((Path(d) / name).read_text(encoding="utf-8"))


def text_of(t):
    return f"{t['subject']} {t['body']}".strip()


def scan(texts):
    return {k: sum(bool(re.search(rx, s, re.I)) for s in texts) for k, rx in PATTERNS.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", default="data")
    ap.add_argument("--output", default="docs/data_audit.md")
    a = ap.parse_args()

    dev = load(a.data_dir, "development_tickets.json")
    val = load(a.data_dir, "validation_tickets.json")
    gt = load(a.data_dir, "ground_truth_responses.json")
    docs = load(a.data_dir, "documentation.json")
    L = []
    w = L.append

    w("# Data audit (Stage 1, Section 5)")
    w(f"\nGenerated by `docs/data_audit.py` from `{a.data_dir}/`. Do not edit by hand.\n")

    w("## Records and fields")
    for name, d in [("development_tickets.json", dev), ("validation_tickets.json", val),
                    ("ground_truth_responses.json", gt), ("documentation.json", docs)]:
        w(f"- `{name}`: {len(d)} records. Fields: {', '.join(sorted({k for x in d for k in x}))}.")
    w(f"- ticket `labels` fields: {', '.join(sorted({k for x in dev for k in x['labels']}))}.")
    w(f"- ticket `history` fields: {', '.join(sorted({k for x in dev for k in x['history']}))}.")

    w("\n## Private-data pattern scan (count of records with a match)")
    w(f"- dev tickets (subject+body, n={len(dev)}): {scan([text_of(t) for t in dev])}")
    w(f"- validation tickets (subject+body, n={len(val)}): {scan([text_of(t) for t in val])}")
    w(f"- ground truth (reference_response, n={len(gt)}): {scan([g['reference_response'] for g in gt])}")
    w(f"- documentation (content, n={len(docs)}): {scan([d['content'] for d in docs])}")
    names = {t["customer_name"] for t in dev + val}
    firsts = {n.split()[0] for n in names}
    in_text = lambda s: any(re.search(rf"\b{re.escape(f)}\b", s) for f in firsts)
    w(f"- customer first names found in ticket text: {sum(in_text(text_of(t)) for t in dev + val)}")
    w(f"- customer first names found in reference responses: {sum(in_text(g['reference_response']) for g in gt)}")
    w(f"- distinct customer_name: {len({t['customer_name'] for t in dev})}; "
      f"distinct customer_id: {len({t['customer_id'] for t in dev})} (dev)")

    w("\n## Customer identity stability (dev)")
    by = defaultdict(list)
    for t in dev:
        by[t["customer_id"]].append(t)
    multi = {k: v for k, v in by.items() if len(v) > 1}
    diff = lambda f: sum(len({t[f] for t in v}) > 1 for v in multi.values())
    w(f"- customer_ids with more than one ticket: {len(multi)} of {len(by)}")
    for f in ("customer_name", "customer_tier", "customer_region", "language_fluency"):
        w(f"- of those, differing `{f}` across tickets: {diff(f)}")
    w(f"- customer_ids shared by dev and validation: "
      f"{len({t['customer_id'] for t in dev} & {t['customer_id'] for t in val})}")

    w("\n## Duplicate ticket texts")
    dc = Counter(text_of(t).lower() for t in dev)
    w(f"- dev: {len(dc)} distinct texts across {len(dev)} tickets; "
      f"{sum(v for v in dc.values() if v > 1)} tickets share a text with another")
    vc = Counter(text_of(t).lower() for t in val)
    w(f"- validation: {len(vc)} distinct texts; tickets whose text also appears in dev: "
      f"{sum(v for k, v in vc.items() if k in dc)} of {len(val)}")
    grp = defaultdict(list)
    for t in dev:
        grp[text_of(t).lower()].append(t)
    rep = [v for v in grp.values() if len(v) > 1]
    conflict = lambda f: sum(len({x["labels"][f] for x in v}) > 1 for v in rep)
    w(f"- repeated dev texts: {len(rep)}. With conflicting labels: intent {conflict('intent')}, "
      f"expected_route {conflict('expected_route')}, urgency {conflict('urgency')}, "
      f"answerable_from_docs {conflict('answerable_from_docs')}")

    w("\n## Ground truth linkage")
    di = {t["ticket_id"]: t for t in dev}
    vi = {t["ticket_id"] for t in val}
    g_dev = [g for g in gt if g["ticket_id"] in di]
    w(f"- reference answers for dev tickets: {len(g_dev)}; for validation tickets: "
      f"{sum(g['ticket_id'] in vi for g in gt)}")
    w(f"- intent matches dev label: {sum(di[g['ticket_id']]['labels']['intent'] == g['intent'] for g in g_dev)}; "
      f"expected_doc_ids match: "
      f"{sum(di[g['ticket_id']]['labels']['expected_doc_ids'] == g['expected_doc_ids'] for g in g_dev)}")
    w(f"- reference answers for tickets not answerable from docs: "
      f"{sum(not di[g['ticket_id']]['labels']['answerable_from_docs'] for g in g_dev)}")
    w(f"- written_by values: {dict(Counter(g['written_by'] for g in gt))}")

    w("\n## Documentation")
    w(f"- categories: {dict(Counter(d['category'] for d in docs))}")
    w(f"- distinct last_reviewed_days_ago values: {sorted({d['last_reviewed_days_ago'] for d in docs})}")
    ids = {d["doc_id"] for d in docs}
    cited = {i for t in dev for i in t["labels"]["expected_doc_ids"]}
    w(f"- doc_ids cited by dev labels but missing from docs: {sorted(cited - ids)}; "
      f"docs never cited: {sorted(ids - cited)}")
    w(f"- dev tickets citing more than one doc: {sum(len(t['labels']['expected_doc_ids']) > 1 for t in dev)}")
    w("")

    md = "\n".join(L)
    Path(a.output).write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
