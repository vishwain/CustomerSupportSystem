"""Local classifier vs PR-02 LLM classifier on the dev hold-out (checklist 5.5, A3; PRD 10.3, NFR-10).

Why: the PRD keeps the local model as default and PR-02 as fallback. This report is the evidence for
that choice: accuracy, calibration and cost of each, on tickets neither was tuned on.

    python docs/classifier_comparison.py                 # local on the full hold-out, LLM on the first 30
    python docs/classifier_comparison.py --llm-limit 0   # local only (no provider calls)
    python docs/classifier_comparison.py --llm-limit 85  # LLM on the whole hold-out (~3 s per call)

Writes docs/classifier_comparison.md and .json. Uses LLM_CACHE if set, so a rerun costs no quota.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from datetime import date
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.ingest import normalise  # noqa: E402
from src.splits import dev_holdout_split  # noqa: E402

BANDS = [(0.0, 0.5), (0.5, 0.7), (0.7, 0.8), (0.8, 0.9), (0.9, 1.0001)]


def evaluate(classify, tickets: list[tuple[Any, dict]]) -> dict[str, Any]:
    rows = []
    for rec, t in tickets:
        c = classify(rec)
        rows.append({"ticket_id": rec.ticket_id, "intent": c.intent, "conf": c.intent_confidence,
                     "intent_ok": c.intent == t["labels"]["intent"], "urgency_ok": c.urgency == t["labels"]["urgency"],
                     "failed": c.failed, "error": c.error, "repaired": bool(c.repairs),
                     "requests": c.requests, "retries": c.retries, "wait_ms": c.rate_limit_wait_ms,
                     "latency_ms": c.latency_ms})
    n = len(rows) or 1
    bands = []
    for lo, hi in BANDS:
        b = [r for r in rows if lo <= r["conf"] < hi and not r["failed"]]
        if b:
            acc = sum(r["intent_ok"] for r in b) / len(b)
            mean = sum(r["conf"] for r in b) / len(b)
            bands.append({"band": f"{lo:.1f}-{min(hi, 1.0):.1f}", "n": len(b), "mean_conf": round(mean, 3),
                          "accuracy": round(acc, 3), "gap_pts": round((mean - acc) * 100, 1)})
    lat = sorted(r["latency_ms"] for r in rows)
    return {
        "n": len(rows),
        "intent_accuracy": round(sum(r["intent_ok"] for r in rows) / n, 4),
        "urgency_accuracy": round(sum(r["urgency_ok"] for r in rows) / n, 4),
        "fallbacks": sum(r["failed"] for r in rows), "errors": dict(Counter(r["error"] for r in rows if r["failed"])),
        "repaired_outputs": sum(r["repaired"] for r in rows),
        "requests": sum(r["requests"] for r in rows), "retries": sum(r["retries"] for r in rows),
        "rate_limit_wait_s": round(sum(r["wait_ms"] for r in rows) / 1000, 1),
        "latency_ms_p50": lat[len(lat) // 2] if lat else 0, "latency_ms_p95": lat[int(0.95 * (len(lat) - 1))] if lat else 0,
        "calibration": bands, "rows": rows,
    }


def to_markdown(r: dict[str, Any]) -> str:
    L = [f"# Classifier comparison ({r['run_date']})", "",
         f"Dev hold-out (NFR-03). Local: `{r['local_version']}`. LLM: `{r.get('llm_model', 'not run')}` with "
         f"PR-02 v1.0. Generated by `docs/classifier_comparison.py`.", "",
         "| Measure | Local | LLM (PR-02) |", "| --- | --- | --- |"]
    lo, ll = r["local"], r.get("llm") or {}
    for k, lab in (("n", "Tickets"), ("intent_accuracy", "Intent accuracy"), ("urgency_accuracy", "Urgency accuracy"),
                   ("fallbacks", "FR-05 fallbacks"), ("repaired_outputs", "Outputs needing repair"),
                   ("requests", "Provider requests"), ("retries", "Retries"), ("rate_limit_wait_s", "Rate-limit wait (s)"),
                   ("latency_ms_p50", "Latency p50 (ms)"), ("latency_ms_p95", "Latency p95 (ms)")):
        L.append(f"| {lab} | {lo.get(k, '')} | {ll.get(k, 'not run')} |")
    for name, res in (("Local", lo), ("LLM", ll)):
        if not res:
            continue
        L += ["", f"Calibration, {name} (mean stated confidence vs observed accuracy; NFR-10 limit 5 pts):", "",
              "| Band | n | Mean confidence | Accuracy | Gap (pts) |", "| --- | --- | --- | --- | --- |"]
        L += [f"| {b['band']} | {b['n']} | {b['mean_conf']} | {b['accuracy']} | {b['gap_pts']} |" for b in res["calibration"]]
    L += ["", "Note: the LLM column covers only the first `--llm-limit` hold-out tickets; compare like with like.", ""]
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dev", default="data/development_tickets.json")
    ap.add_argument("--llm-limit", type=int, default=30)
    ap.add_argument("--out", default="docs/classifier_comparison")
    a = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    from src.classify import LLMClassifier, LocalClassifier
    from src.retrieve import SentenceTransformerEmbedder

    dev = json.loads(Path(a.dev).read_text(encoding="utf-8"))
    _, hold = dev_holdout_split(dev)
    hs = set(hold)
    tickets = [(normalise(t, i), t) for i, t in enumerate(dev) if t["ticket_id"] in hs]
    tickets = [(r, t) for r, t in tickets if r.ok]

    local = LocalClassifier(SentenceTransformerEmbedder()).load_or_train()
    out: dict[str, Any] = {"run_date": date.today().isoformat(), "local_version": local.version,
                           "local": evaluate(local.classify, tickets)}
    if a.llm_limit > 0:
        from src.llm import client_from_env
        llm = LLMClassifier(client_from_env())
        sub = tickets[: a.llm_limit]
        out["llm_model"] = llm.client.model
        out["llm"] = evaluate(llm.classify, sub)
        out["local_same_subset"] = evaluate(local.classify, sub)
    p = Path(a.out)
    p.with_suffix(".json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    md = to_markdown(out)
    if "local_same_subset" in out:
        s = out["local_same_subset"]
        md += (f"Local on the same {s['n']} tickets as the LLM: intent {s['intent_accuracy']:.1%}, "
               f"urgency {s['urgency_accuracy']:.1%}.\n")
    p.with_suffix(".md").write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
