"""Guardrail evidence (5b.4): collect every blocked output and its logged decision into one place for the
guardrail table and the demo video.

Sources (all real runs; nothing is re-run here):
  - the guardrail demo (docs/guardrail_demo.py): crafted model outputs through the real Validate code, with
    the real embedding model and retrieved passage; one validation row each in its decisions.db
  - the engineered-ticket run (tests/fixtures/engineered_tickets.json through the full pipeline)
  - validation run 11 (5.17): the two drafts Validate blocked

Usage:
    python docs/guardrail_evidence.py --demo-dir evaluation/results/2026-11-19_guardrail_demo \
        --engineered-dir evaluation/results/2026-11-19_engineered_v2 \
        --run-dir evaluation/results/validation_5.17_official --out evaluation/results/guardrail_evidence
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sqlite3
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))


def demo_cases() -> dict[str, dict[str, Any]]:
    spec = importlib.util.spec_from_file_location("gd", Path(__file__).with_name("guardrail_demo.py"))
    gd = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gd)
    cs = gd.cases("<retrieved passage>", ["<sentence copied from the retrieved passage>"])
    return {c["id"]: c for c in cs}


def rows(db: Path, stage: str | None = None, run_id: str | None = None) -> list[dict[str, Any]]:
    con = sqlite3.connect(db)
    con.row_factory = sqlite3.Row
    q, a = "SELECT * FROM decisions WHERE 1=1", []
    if stage:
        q, a = q + " AND stage = ?", a + [stage]
    if run_id:
        q, a = q + " AND run_id = ?", a + [run_id]
    out = [dict(r) for r in con.execute(q, a)]
    con.close()
    for r in out:
        for k in ("prediction", "guardrail_results", "sources_used"):
            try:
                r[k] = json.loads(r[k])
            except (TypeError, ValueError):
                pass
    return out


def collect(demo_dir: Path, eng_dir: Path, run_dir: Path) -> dict[str, Any]:
    ev: dict[str, Any] = {"demo": [], "engineered": [], "validation_run": []}
    cases = demo_cases()
    for r in rows(demo_dir / "decisions.db", "validation"):
        cid = r["ticket_id"].replace("DEMO-", "")
        c = cases.get(cid, {})
        offending = [s["text"] for s in c.get("sentences", []) if not s["text"].startswith("<")]
        ev["demo"].append({"case": cid, "what": c.get("what"), "expected": c.get("expect"),
                           "offending_output": offending or ["(the clean answer; see 'what')"],
                           "ticket_text": c.get("ticket_text"), "confidence": c.get("confidence"),
                           "action": r["action_taken"], "blocked_by": (r["prediction"] or {}).get("blocked_by", []),
                           "reason": r["reason"], "decision_id": r["decision_id"],
                           "guardrail_results": r["guardrail_results"]})
    for line in (eng_dir / "results.jsonl").read_text(encoding="utf-8").splitlines():
        x = json.loads(line)
        ev["engineered"].append({k: x[k] for k in ("ticket_id", "action", "rule_fired", "reason")})
    info = json.loads((run_dir / "run_info.json").read_text(encoding="utf-8"))
    db = Path(info["db_path"])
    gen = {r["ticket_id"]: r for r in rows(db, "generation", info["run_id"])}
    for v in rows(db, "validation", info["run_id"]):
        if v["action_taken"] != "block":
            continue
        g = gen.get(v["ticket_id"]) or {}
        ev["validation_run"].append({
            "ticket_id": v["ticket_id"], "run_id": info["run_id"], "decision_id": v["decision_id"],
            "blocked_by": (v["prediction"] or {}).get("blocked_by", []), "reason": v["reason"],
            "blocked_draft": [s.get("text") for s in (g.get("prediction") or {}).get("sentences", [])],
            "cited": [s["passage_id"] for s in g.get("sources_used", [])],
            "similarities": ((v["prediction"] or {}).get("details", {}).get("grounding", {}) or {}).get("similarities")})
    return ev


def to_markdown(ev: dict[str, Any]) -> str:
    L = ["# Guardrail evidence (5b.4): blocked outputs", "",
         "Every output a guardrail blocked, with the decision-log row that recorded it. Nothing here was sent to a "
         "customer. Generated by `docs/guardrail_evidence.py` from existing runs.", "",
         "## 1. Guardrail demo: crafted outputs through the real Validate code", "",
         "Real embedding model, real retrieved passage, real Validate; the model output is crafted so each check "
         "must fire. Log: `evaluation/results/2026-11-19_guardrail_demo/decisions.db`.", ""]
    for d in ev["demo"]:
        L += [f"### {d['case']}: {d['what']}", "",
              "Blocked output:" if d["action"] == "block" else "Output (passed):", ""]
        for s in d["offending_output"]:
            L.append(f"> {s}")
        if d["ticket_text"]:
            L += ["", f"Ticket text: > {d['ticket_text'][:200]}"]
        if d["confidence"] is not None:
            L += ["", f"Intent confidence given: {d['confidence']}"]
        L += ["", f"Result: **{d['action']}**, fired: {', '.join(d['blocked_by']) or 'none'}. Reason logged: "
              f"{d['reason']}", f"Decision id: `{d['decision_id']}`", ""]
    L += ["## 2. Engineered tickets through the full pipeline (live provider)", "",
          "`tests/fixtures/engineered_tickets.json`, run `20261119T145250Z_engineered_tickets_dcdf`.", "",
          "| Ticket | Final | Rule | Reason logged |", "| --- | --- | --- | --- |"]
    for x in ev["engineered"]:
        L.append(f"| {x['ticket_id']} | {x['action']} | {x['rule_fired']} | {x['reason'][:180]} |")
    L += ["", "## 3. Validation run 11: drafts Validate blocked (live provider output)", ""]
    for x in ev["validation_run"]:
        L += [f"### {x['ticket_id']}", "", f"Blocked by {', '.join(x['blocked_by'])}. Reason logged: {x['reason']}",
              f"Run `{x['run_id']}`, decision id `{x['decision_id']}`. Cited: {', '.join(x['cited'])}. "
              f"Sentence similarities: {x['similarities']}.", "", "Blocked draft (never sent):", ""]
        for i, s in enumerate(x["blocked_draft"], 1):
            L.append(f"{i}. {s}")
        L.append("")
    L += ["The 5.18 review judged both blocks false positives: the drafts are word-for-word from the article "
          "(revision log, Section 4)."]
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--demo-dir", default="evaluation/results/2026-11-19_guardrail_demo")
    ap.add_argument("--engineered-dir", default="evaluation/results/2026-11-19_engineered_v2")
    ap.add_argument("--run-dir", default="evaluation/results/validation_5.17_official")
    ap.add_argument("--out", default="evaluation/results/guardrail_evidence")
    a = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ev = collect(Path(a.demo_dir), Path(a.engineered_dir), Path(a.run_dir))
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "blocked_outputs.json").write_text(json.dumps(ev, indent=2), encoding="utf-8")
    (out / "blocked_outputs.md").write_text(to_markdown(ev), encoding="utf-8")
    print(f"{len(ev['demo'])} demo cases, {len(ev['engineered'])} engineered tickets, "
          f"{len(ev['validation_run'])} blocked drafts from the validation run -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
