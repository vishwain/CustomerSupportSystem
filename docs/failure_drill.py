"""5.11 failure drill (A11): force every failure case through the real pipeline and show each one ends in
an escalation with a logged reason, and that every run reconciles (tickets in = final rows out).

Runs evaluation.harness four times on tests/fixtures/failure_tickets.json (malformed records, odd
encodings, two tickets with no relevant docs, readable tickets that reach Generate):

  1. normal     real key, empty cache                        -> baseline, fills the cache
  2. rerun      same file, same cache                        -> provider_requests must be 0
  3. bad_key    OPENROUTER_API_KEY replaced, cache off       -> no retry, circuit opens, all escalate
  4. timeout    LLM_TIMEOUT_S=0.01, cache off                -> retries, then escalate with provider reason

The real key is never printed or written: run 3 only overrides it in the child process environment.
Rate limiting cannot be forced on demand; tests/test_failures.py covers it with a scripted 429.

Usage (repo root):  python docs/failure_drill.py
Output: evaluation/results/<date>_failure_drill/failure_drill.md (+ one harness folder per run)
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import time
from datetime import date
from pathlib import Path

FIXTURE = "tests/fixtures/failure_tickets.json"
SCENARIOS = [
    ("normal", {}, []),
    ("rerun", {}, []),
    ("bad_key", {"OPENROUTER_API_KEY": "sk-or-v1-invalid-key-for-failure-drill"}, ["--no-cache"]),
    ("timeout", {"LLM_TIMEOUT_S": "0.01"}, ["--no-cache"]),
]


def run_one(name: str, env_over: dict, flags: list[str], out_root: Path, cache_dir: Path) -> dict:
    out = out_root / name
    # LLM_CACHE=1 set here so a "LLM_CACHE=0" line in .env cannot switch the cache off for runs 1-2
    env = {**os.environ, "LLM_CACHE": "1", "LLM_CACHE_DIR": str(cache_dir), "PYTHONIOENCODING": "utf-8", **env_over}
    t0 = time.perf_counter()
    p = subprocess.run([sys.executable, "-m", "evaluation.harness", "--input", FIXTURE, "--output", str(out),
                        "--quiet", *flags], env=env, capture_output=True, text=True, encoding="utf-8",
                       errors="replace")
    wall = time.perf_counter() - t0
    rec = json.loads((out / "reconcile.json").read_text(encoding="utf-8")) if (out / "reconcile.json").exists() else {}
    res = ([json.loads(x) for x in (out / "results.jsonl").read_text(encoding="utf-8").splitlines()]
           if (out / "results.jsonl").exists() else [])
    met = json.loads((out / "metrics_report.json").read_text(encoding="utf-8")) if (out / "metrics_report.json").exists() else {}
    return {"name": name, "exit": p.returncode, "wall_s": round(wall, 1), "reconcile_ok": rec.get("ok"),
            "final_rows": rec.get("final_rows"), "results": res, "metrics": met,
            "stderr_tail": [l for l in p.stderr.splitlines() if "WARNING" in l or "ALERT" in l][-5:]}


def cases() -> dict[str, str]:
    raw = json.loads(Path(FIXTURE).read_text(encoding="utf-8"))
    out = {}
    for i, t in enumerate(raw):
        if isinstance(t, dict):
            out[t.get("ticket_id") or f"ROW-{i + 1:04d}"] = t.get("case", "")
        else:
            out[f"ROW-{i + 1:04d}"] = "record is not an object"
    return out


def to_markdown(runs: list[dict]) -> tuple[str, bool]:
    c = cases()
    L = [f"# Failure drill (5.11), {date.today().isoformat()}", "",
         f"Input `{FIXTURE}` ({len(c)} records). Generated by `docs/failure_drill.py`.", "",
         "| Run | Exit | Reconciles | Final rows | Escalated | Sent | Provider requests | Cache hits | Degraded | Wall s |",
         "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in runs:
        m, res = r["metrics"], r["results"]
        L.append(f"| {r['name']} | {r['exit']} | {r['reconcile_ok']} | {r['final_rows']} | "
                 f"{sum(x['action'] == 'escalate' for x in res)} | {sum(x['action'] == 'auto_respond' for x in res)} | "
                 f"{m.get('provider_requests', '?')} | {m.get('generation_cache_hits', '?')} | "
                 f"{m.get('degraded_mode_tickets', '?')} | {r['wall_s']} |")
    for r in runs:
        L += ["", f"## {r['name']}", "", "| Ticket | Case | Final | Error | Rule | Reason |", "| --- | --- | --- | --- | --- | --- |"]
        for x in r["results"]:
            reason = (x["reason"] or "").replace("|", "/").replace("\n", " ")
            L.append(f"| {x['ticket_id']} | {c.get(x['ticket_id'], '')} | {x['action']} | {x['error']} | "
                     f"{x['rule_fired']} | {reason[:160]} |")
        if r["stderr_tail"]:
            L += ["", "Warnings: " + "; ".join(r["stderr_tail"])]
    checks = {
        "every run exits 0 and reconciles": all(r["exit"] == 0 and r["reconcile_ok"] for r in runs),
        "rerun spends no provider calls": next(r for r in runs if r["name"] == "rerun")["metrics"].get("provider_requests") == 0,
        "bad key: nothing sent, every generation error is provider_down":
            all(x["action"] == "escalate" for x in runs[2]["results"])
            and all(x["error"] == "provider_down" for x in runs[2]["results"] if x.get("generation")),
        "timeout: nothing sent, generation errors are timeout or provider_down":
            all(x["action"] == "escalate" for x in runs[3]["results"])
            and all(x["error"] in ("timeout", "provider_down") for x in runs[3]["results"] if x.get("generation")),
        "no-docs tickets: escalated, no passage, no draft, no model call, in every run":
            all(x["action"] == "escalate" and not x.get("generation")
                and x["escalation_package"].get("passages") == "none found"
                for r in runs for x in r["results"] if x["ticket_id"].startswith("FAIL-NODOCS")),
    }
    L += ["", "## Checks", ""] + [f"- {'PASS' if ok else 'FAIL'}: {k}" for k, ok in checks.items()] + [""]
    return "\n".join(L), all(checks.values())


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    out_root = Path(f"evaluation/results/{date.today().isoformat()}_failure_drill")
    out_root.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        cache = Path(tmp) / "llm_cache"  # empty at the start, shared by runs 1 and 2
        runs = []
        for name, env_over, flags in SCENARIOS:
            print(f"running {name} ...", flush=True)
            runs.append(run_one(name, env_over, flags, out_root, cache))
    md, ok = to_markdown(runs)
    (out_root / "failure_drill.md").write_text(md, encoding="utf-8")
    print(md)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
