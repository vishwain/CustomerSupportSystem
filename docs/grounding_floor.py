"""Grounding floor and guardrail false-positive check (checklist 5.9; PRD FR-22 item 3, FR-23, NFR-04).

Floor (FR-22): for each sentence of the 200 senior-agent reference answers, the best embedding similarity to
any chunk of that ticket's expected articles. The floor is the 5th percentile: 95% of sentences a senior
agent wrote while answering from the docs score at or above it. Greeting and sign-off sentences ("Thanks
for getting in touch", "Hope this helps") are left out: they are not claims and Generate does not write them.

False positives: the private-data and commitment patterns are run over all 200 reference answers and all 29
articles, which contain no private data and no promises. Any hit there would block a correct answer.

    python docs/grounding_floor.py                  # report to evaluation/results/<date>_grounding_floor/
    python docs/grounding_floor.py --write-config   # also sets grounding_floor in config/guardrails.json
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import pii  # noqa: E402
from src.guardrails import GuardrailConfig, split_sentences  # noqa: E402

PERCENTILE = 5
PLEASANTRY = re.compile(r"^(thanks|thank you|hope (this|that) helps|happy to help|let us know|please (do )?let us|"
                        r"if (this|that) (does not|doesn't)|apolog|sorry|i appreciate|we appreciate|good question|"
                        r"kind regards|best regards|if you work through|do let me know|please reply|reply with)", re.I)


def reference_sentences(refs: list[dict[str, Any]]) -> list[tuple[str, str, list[str]]]:
    out = []
    for r in refs:
        if not r.get("expected_doc_ids"):
            continue
        for s in split_sentences(r["reference_response"].replace("\n", " ")):
            if len(s.split()) >= 5 and not PLEASANTRY.match(s):
                out.append((r["ticket_id"], s, r["expected_doc_ids"]))
    return out


def compute_floor(embedder, passages, refs) -> dict[str, Any]:
    import numpy as np

    by_doc: dict[str, list] = {}
    for p in passages:
        by_doc.setdefault(p.doc_id, []).append(p)
    P = np.asarray(embedder.encode([p.text for p in passages]))
    idx = {p.passage_id: i for i, p in enumerate(passages)}
    sents = reference_sentences(refs)
    S = np.asarray(embedder.encode([s for _, s, _ in sents]))
    sims = []
    for (tid, s, docs), v in zip(sents, S):
        rows = [idx[p.passage_id] for d in docs for p in by_doc.get(d, [])]
        sims.append(float((P[rows] @ v).max()) if rows else 0.0)
    arr = np.asarray(sims)
    floor = round(float(np.percentile(arr, PERCENTILE)), 3)
    lowest = sorted(zip(sims, sents), key=lambda x: x[0])[:8]
    return {
        "n_sentences": len(sims), "n_answers": len({t for t, _, _ in sents}), "floor": floor,
        "percentiles": {str(q): round(float(np.percentile(arr, q)), 3) for q in (1, 5, 10, 25, 50, 75)},
        "lowest_examples": [{"ticket_id": t, "similarity": round(x, 3), "sentence": s[:160]} for x, (t, s, _) in lowest],
    }


def false_positives(refs, docs, cfg: GuardrailConfig) -> dict[str, Any]:
    commit = [re.compile(p, re.I) for p in cfg.commitment_patterns + cfg.promise_patterns]
    hits_ref = [{"ticket_id": r["ticket_id"], "phrase": m.group(0)} for r in refs for rx in commit
                for m in rx.finditer(r["reference_response"])]
    return {
        "pii_in_references": sum(bool(pii.find(r["reference_response"])) for r in refs),
        "pii_in_articles": sum(bool(pii.find(d["content"])) for d in docs),
        "commitment_hits_in_references": hits_ref,
        "commitment_hits_in_articles": [{"doc_id": d["doc_id"], "phrase": m.group(0)} for d in docs for rx in commit
                                        for m in rx.finditer(d["content"])],
    }


def to_markdown(r: dict[str, Any]) -> str:
    f, fp = r["floor"], r["false_positives"]
    L = [f"# Grounding floor and guardrail false positives ({r['run_date']})", "",
         f"Embedding model `{r['embedding_model']}`, chunking `{r['chunking']}`. Generated by "
         "`docs/grounding_floor.py`.", "",
         "## Grounding floor (FR-22 item 3)", "",
         f"{f['n_sentences']} claim sentences from {f['n_answers']} reference answers (greetings and sign-offs "
         "left out). Similarity = best cosine between the sentence and any chunk of the ticket's expected articles.", "",
         "| Percentile | " + " | ".join(f["percentiles"]) + " |",
         "| --- | " + " | ".join("---" for _ in f["percentiles"]) + " |",
         "| Similarity | " + " | ".join(str(v) for v in f["percentiles"].values()) + " |", "",
         f"**Floor = {f['floor']}** ({PERCENTILE}th percentile): a generated sentence must reach this against its "
         "cited passages. About 5% of senior-agent sentences fall below it, so the floor will also block some correct "
         "answers; the alternative, a lower floor, lets more unsupported claims through.", "",
         "Lowest-scoring reference sentences (what the floor rejects):", ""]
    L += [f"- {x['ticket_id']} ({x['similarity']}): {x['sentence']}" for x in f["lowest_examples"]]
    L += ["", "## False positives on text that must pass", "",
          "| Check | Text scanned | Hits |", "| --- | --- | --- |",
          f"| Private data | 200 reference answers | {fp['pii_in_references']} |",
          f"| Private data | 29 articles | {fp['pii_in_articles']} |",
          f"| Commitments | 200 reference answers | {len(fp['commitment_hits_in_references'])} |",
          f"| Commitments | 29 articles | {len(fp['commitment_hits_in_articles'])} |", ""]
    if fp["commitment_hits_in_references"]:
        L += ["Reference hits (a correct answer this pattern list would block):", ""]
        L += [f"- {h['ticket_id']}: '{h['phrase']}'" for h in fp["commitment_hits_in_references"][:10]]
    if fp["commitment_hits_in_articles"]:
        L += ["", "Article phrases (allowed when the answer cites that article; FR-23):", ""]
        L += [f"- {h['doc_id']}: '{h['phrase']}'" for h in fp["commitment_hits_in_articles"]]
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--refs", default="data/ground_truth_responses.json")
    ap.add_argument("--out-dir", default=None)
    ap.add_argument("--write-config", action="store_true")
    ap.add_argument("--config-path", default="config/guardrails.json")
    a = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    from src.retrieve import CONFIGS, SentenceTransformerEmbedder, chunk_docs, load_config, load_docs

    emb = SentenceTransformerEmbedder()
    rc = load_config()
    docs = load_docs()
    refs = json.loads(Path(a.refs).read_text(encoding="utf-8"))
    r = {"run_date": date.today().isoformat(), "embedding_model": emb.name, "chunking": rc.chunking,
         "floor": compute_floor(emb, chunk_docs(docs, CONFIGS[rc.chunking]), refs),
         "false_positives": false_positives(refs, docs, GuardrailConfig.load(a.config_path))}
    out = Path(a.out_dir or f"evaluation/results/{r['run_date']}_grounding_floor")
    out.mkdir(parents=True, exist_ok=True)
    (out / "grounding_floor.json").write_text(json.dumps(r, indent=2), encoding="utf-8")
    md = to_markdown(r)
    (out / "grounding_floor.md").write_text(md, encoding="utf-8")
    print(md)
    if a.write_config:
        p = Path(a.config_path)
        cfg = json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}
        cfg.update({"grounding_floor": r["floor"]["floor"], "set_on": r["run_date"],
                    "floor_evidence": str(out / "grounding_floor.md").replace("\\", "/")})
        p.write_text(json.dumps(cfg, indent=2) + "\n", encoding="utf-8")
        print(f"\nwrote grounding_floor {r['floor']['floor']} to {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
